CREATE DATABASE DescarteSustentavel;

USE DescarteSustentavel;

CREATE TABLE TBL_DESCARTE_ELETRONICO (
     ID_DESCARTE BIGINT IDENTITY(1,1) PRIMARY KEY,
     TX_MATRICULA_ALUNO VARCHAR(20) NOT NULL,
     TX_TIPO_ITEM VARCHAR(30) NOT NULL,
     NR_PESO_GRAMAS FLOAT NOT NULL,
     NR_PONTOS_GERADOS INT NOT NULL,
     CHK_VALIDADO BIT NOT NULL
);